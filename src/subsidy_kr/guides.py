def faq_pairs(guide: Dict[str, Any]) -> List[Tuple[str, str]]:
    """FAQPage JSON-LD 에 넣을 질문·답 쌍(페이지 본문과 같은 문장을 쓴다)."""
    topic = guide["topic"]
    return [
        (guide["question"], guide["one_line"]),
        (f"{topic} 신청 전에 무엇을 확인해야 하나요?", " ".join(guide["conditions"])),
        (f"{topic} 신청은 어디서 하나요?", guide["apply"]),
        (f"{topic}에서 흔히 하는 착각은 무엇인가요?", " ".join(guide["pitfalls"])),
    ]


def _esc(value: Any) -> str:
    return html.escape(str(value or ""), quote=True)


def _related(catalog: Any, guide: Dict[str, Any], limit: int = 5) -> Tuple[int, List[Any]]:
    """그 주제의 실제 공고 — 마감된 것은 빼고, 같은 트랙을 먼저 보여 준다."""
    memo_key = f"guides_related:{guide['slug']}:{limit}"
    cached = catalog.memo.get(memo_key) if hasattr(catalog, "memo") else None
    if cached is not None:
        return cached
    seen: Dict[str, Any] = {}
    ordered: List[Any] = []
    for term in guide.get("keywords") or []:
        for svc in catalog.search(term, limit=12):
            if svc.service_id in seen:
                continue
            seen[svc.service_id] = svc
            ordered.append(svc)
    rows = [svc for svc in ordered if not svc.is_expired]
    want = guide.get("track") or "personal"
    want = "business" if want == "agent" else want
    # 검색 점수 순서를 살리면서, 같은 트랙을 먼저 보여 준다(정렬은 안정 정렬).
    rows.sort(key=lambda svc: (svc.track != want, svc.is_business))
    result = (len(rows), rows[:limit])
    if hasattr(catalog, "memo"):
        catalog.memo[memo_key] = result
    return result


